// Use the existing height-field jump controller on authored props; the arena rim has no jumpable height.
export function instantCombatJumpColliders(mapId: string | null | undefined, feetY: number) {
  return instantCombatMap(mapId).colliders.filter(c => c.height === undefined || c.height > JUMP_SPEED ** 2 / (2 * JUMP_GRAVITY) || c.height > feetY + .001);
}
export function instantCombatJumpFloor(mapId: string | null | undefined, x: number, z: number) {
  let floor = 0;
  for (const c of propColliders[instantCombatMap(mapId).id]) if (Math.abs(x - c.x) <= c.halfWidth! + PLAYER_RADIUS
    && Math.abs(z - c.z) <= c.halfDepth! + PLAYER_RADIUS) floor = Math.max(floor, c.height!);
  return floor;
}

// Props are obstacles to clear, not safe combat platforms. A short landing slides onto clear ground.
export function instantCombatJumpLanding(mapId: string | null | undefined, x: number, z: number) {
  const map = instantCombatMap(mapId);
  // Use the exact swept-circle collision check, including narrow gaps beside clustered bones.
  for (let r = .25; r <= 4; r += .25) for (let i = 0; i < 64; i++) {
    const point = { x: x + Math.sin(i * Math.PI / 32) * r, z: z + Math.cos(i * Math.PI / 32) * r };
    if (canTraverse(point, point, map.colliders, map.bounds)) return point;
  }
  return instantCombatPosition(mapId, x, z, .6);
}

export function instantCombatPosition(mapId: string | null | undefined, x: number, z: number, clearance = .4) {
  const map = instantCombatMap(mapId);
  const free = (px: number, pz: number) => Math.hypot(px, pz) < map.radius - clearance && map.colliders.every(c =>
    c.halfWidth !== undefined ? Math.hypot(Math.max(0, Math.abs(px - c.x) - c.halfWidth), Math.max(0, Math.abs(pz - c.z) - c.halfDepth!)) > clearance
      : Math.hypot(px - c.x, pz - c.z) > c.r + clearance);
  if (Number.isFinite(x) && Number.isFinite(z)) {
    const distance = Math.hypot(x, z), scale = Math.min(1, (map.radius - clearance - .1) / Math.max(1, distance)); x *= scale; z *= scale;
    if (free(x, z)) return { x, z };
    for (let ring = .5; ring <= map.radius * 2; ring += .5) for (let i = 0; i < Math.ceil(ring * 12); i++) {
      const angle = i / Math.ceil(ring * 12) * Math.PI * 2, px = x + Math.sin(angle) * ring, pz = z + Math.cos(angle) * ring;
      if (free(px, pz)) return { x: px, z: pz };
    }
  }
  return { ...map.boss }; // The authored ritual platform is kept clear during conversion.
}
