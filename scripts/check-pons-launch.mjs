import assert from 'node:assert/strict';
import { Interface, MaxUint256, ZeroAddress, ZeroHash } from 'ethers';
import { CHAIN_ID, ROUTER, RBLX, compilePonsInterfaces, buildTokenParams, quoteInitialBuy, minimumTokensOut, buildLaunchTransaction } from './pons-launch-chain.mjs';

const creator = '0x1111111111111111111111111111111111111111';
const salt = `0x${'12'.repeat(32)}`;
const state = { creator, configId: 0n, launchFee: 500_000_000_000_000n, expectedEconomics: `0x${'ab'.repeat(32)}`, config: { supply: 10n ** 27n, curveFeeBps: 100n }, pairEconomics: { phantomQuote: 99_568_605_851_979_347_398n, graduationThreshold: 248_921_514_629_948_368_496n } };
const config = { name: 'Mossvale', symbol: 'MOSS', creatorTaxBps: 0, buybackEnabled: false };
const quoteIn = 550_482_536_387_130_000n;
const quote = quoteInitialBuy(quoteIn, state);
const net = quoteIn - quoteIn / 100n;
assert.equal(quote.tokensOut, net * 10n ** 27n / (state.pairEconomics.phantomQuote + net));
assert.equal(quote.spent, quoteIn);
assert.equal(quote.refund, 0n);
assert.equal(minimumTokensOut(1n), 1n, 'Rounding cannot waive the output minimum');
assert.equal(minimumTokensOut(10_001n), 9_901n);
const clamped = quoteInitialBuy(1000n * 10n ** 18n, state);
const reserved = state.config.supply * state.pairEconomics.phantomQuote / (state.pairEconomics.phantomQuote + state.pairEconomics.graduationThreshold);
assert.equal(clamped.tokensOut, state.config.supply - reserved);
assert.ok(clamped.refund > 0n && clamped.spent + clamped.refund === 1000n * 10n ** 18n);
const minTokensOut = minimumTokensOut(quote.tokensOut);
const tx = buildLaunchTransaction({ config, creator, salt, state, quoteIn, minTokensOut });
const abis = compilePonsInterfaces();
assert.equal(tx.to, ROUTER);
assert.equal(tx.chainId, CHAIN_ID);
assert.equal(tx.value, state.launchFee, 'RBLX dev buy is not sent as native ETH');
const router = new Interface(abis.routerAbi);
const args = router.decodeFunctionData('launchAndBuy', tx.data);
assert.equal(args.params.creatorFeeRecipient, creator);
assert.equal(args.recipient, creator);
assert.equal(args.pairToken, RBLX);
assert.equal(args.quoteIn, quoteIn);
assert.equal(args.minTokensOut, minTokensOut);
assert.equal(args.params.expectedEconomics, state.expectedEconomics);
assert.equal(args.params.salt, salt);
assert.equal(args.params.creatorTaxBps, 0n);
assert.equal(args.params.buybackEnabled, false);
assert.equal(args.snipeTaxExemptions.length, 0);
assert.equal(new Interface(abis.factoryAbi).getEvent('TokenLaunched').inputs.length, 6);
assert.deepEqual(Array.from(router.decodeFunctionResult('launchAndBuy', router.encodeFunctionResult('launchAndBuy', [creator, ROUTER, quote.tokensOut]))), [creator, ROUTER, quote.tokensOut]);
for (const amount of [0n, -1n, 1, MaxUint256 + 1n]) assert.throws(() => quoteInitialBuy(amount, state));
assert.throws(() => quoteInitialBuy(quoteIn, { ...state, config: { ...state.config, curveFeeBps: 10_000n } }));
for (const amount of [0n, -1n]) assert.throws(() => minimumTokensOut(amount));
assert.throws(() => minimumTokensOut(quote.tokensOut, 101n));
for (const minimum of [0n, minTokensOut - 1n, quote.tokensOut + 1n]) assert.throws(() => buildLaunchTransaction({ config, creator, salt, state, quoteIn, minTokensOut: minimum }));
for (const patch of [{ name: '' }, { creatorTaxBps: 1 }, { buybackEnabled: true }, { socials: { twitter: 123 } }]) assert.throws(() => buildTokenParams({ ...config, ...patch }, creator, state.expectedEconomics, salt));
assert.throws(() => buildTokenParams(config, ZeroAddress, state.expectedEconomics, salt));
assert.throws(() => buildTokenParams(config, creator, ZeroHash, salt));
assert.throws(() => buildTokenParams(config, creator, state.expectedEconomics, ZeroHash));
assert.throws(() => buildLaunchTransaction({ config: { ...config, launchConfigId: 1 }, creator, salt, state, quoteIn, minTokensOut }));
console.log('PONS interfaces, launch calldata, fee rounding, partial fills, and minimum-output checks passed.');
