import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as THREE from 'three';
import { graphics, GRAPHICS_PRESETS } from '../src/graphics-settings.ts';
import { createDayNightCycle } from '../src/day-night.ts';

const source = readFileSync('src/main.ts', 'utf8');
const code = source.slice(source.indexOf('function applyGraphics(){'), source.indexOf('function openSettings(){'));
const renderer = { shadowMap: { enabled: true, type: THREE.PCFSoftShadowMap }, setPixelRatio(value) { this.pixelRatio = value; } };
const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera(52, 1, .1, 500), sun = new THREE.DirectionalLight();
const material = new THREE.MeshStandardMaterial(), other = new THREE.MeshBasicMaterial();
scene.add(new THREE.Mesh(new THREE.BoxGeometry(), [material, other]));
sun.shadow.mapSize.set(2048, 2048);
const cycle = createDayNightCycle(scene, new THREE.HemisphereLight(), sun);
const context = vm.createContext({ THREE, graphics, renderer, scene, camera, sun, renderedInstance:null,isArenaInstance:id=>id.startsWith('arena:'),devicePixelRatio: 2, previewRenderer: undefined, previewScene: undefined });
vm.runInContext(ts.transpileModule(code, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context);
const apply = () => vm.runInContext('applyGraphics()', context);
const fog = dungeon => { context.renderedInstance=dungeon?'dungeon:test':null;cycle.update(0, 'greenwood', dungeon, new THREE.Vector3(), camera); vm.runInContext('applyGraphicsFog()', context); };
let disposed = 0;
sun.shadow.map = { dispose() { disposed++; } };
Object.assign(graphics, GRAPHICS_PRESETS.low);apply();fog(false);
assert.equal(renderer.pixelRatio, .8, 'low reduces each drawing-buffer dimension to half at capped DPR');
assert.equal(renderer.shadowMap.enabled, false);
assert.equal(sun.shadow.map, null);assert.equal(disposed, 1, 'release old shadow target');
assert.equal(camera.far, 200);assert.equal(scene.fog.far, 120);assert.equal(scene.fog.near, 42);
assert(material.version > 0 && other.version > 0, 'all materials recompile when shadow use changes');
const version = material.version;
apply();assert.equal(material.version, version, 'unrelated settings do not recompile every scene material');
Object.assign(graphics, GRAPHICS_PRESETS.medium);apply();
assert.equal(renderer.shadowMap.type, THREE.PCFShadowMap);assert.equal(sun.shadow.mapSize.x, 1024);
Object.assign(graphics, GRAPHICS_PRESETS.high);apply();fog(false);
assert.equal(renderer.pixelRatio, 1.6);assert.equal(renderer.shadowMap.enabled, true);
assert.equal(sun.shadow.mapSize.x, 2048);assert.equal(camera.far, 500);assert.equal(scene.fog.far, 420, 'higher distance restores fog after a lower setting');
fog(true);assert.equal(scene.fog.far, 105, 'dungeon atmosphere remains readable');
assert.equal(camera.far,137,'dungeon camera stops submitting rooms behind opaque fog');
context.renderedInstance='arena:test';vm.runInContext('applyGraphicsFog()',context);assert.equal(camera.far,500,'arena retains its full viewing range');
fog(false);assert.equal(camera.far,500,'leaving a dungeon restores overworld viewing range');
context.devicePixelRatio = 1;apply();assert.equal(renderer.pixelRatio, 1, 'normal displays are not supersampled');
cycle.dispose();
assert(source.includes('dayNight.update(Date.now()+serverOffset,worldZone,!!renderedInstance&&!usesArenaWorld(renderedInstance),position,camera,isRaidInstance(renderedInstance),isInstantCombatInstance(renderedInstance)?instantCombat?.run?.mapId:undefined);applyGraphicsFog();'), 'day/night updates cannot overwrite graphics distance');
assert(source.includes("mountGraphicsSettings($('panel-content'),applyGraphics)"));
console.log('PASS: resolution, shadow shaders and target disposal, distance/fog restoration, dungeon visibility, DPI changes and Options wiring.');
