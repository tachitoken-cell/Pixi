import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { runInNewContext } from 'node:vm';
const source = stripTypeScriptTypes(readFileSync(new URL('../src/native-client.ts', import.meta.url), 'utf8')).replace(/^export /gm, '');
function render({ native = false, platform, version, build, ua = '', device = '', touch = 0 } = {}) {
  const window = { __MOSSVALE_NATIVE__: native, addEventListener() {} };
  if (platform) window.__MOSSVALE_NATIVE_APP__ = { platform, version, build };
  return runInNewContext(source + '\nrenderUpdateGuidance();', { window, navigator: { userAgent: ua, platform: device, maxTouchPoints: touch } });
}
const web = render();
assert.match(web, /Game fixes and content load from Mossvale automatically/);
assert.match(web, /playing in a web browser/);
assert(!web.includes('href='), 'browser play does not prompt for a store update');
const legacy = render({ native: true, ua: 'Android' });
assert.match(legacy, /app version: <strong>unavailable/);
assert.match(legacy, /device’s app settings or TestFlight/);
assert(legacy.includes('play.google.com/store/apps/details?id=world.mossvale.game'));
assert(!legacy.includes('apps.apple.com'));
const ipad = render({ native: true, device: 'MacIntel', touch: 5 });
assert(ipad.includes('apps.apple.com/app/id6811825860'));
assert(!ipad.includes('play.google.com'));
const current = render({ native: true, platform: 'apple', version: '1.0.1', build: '123', ua: 'Android' });
assert.match(current, /app version: <strong>1.0.1/);
assert.match(current, /app build: <strong>123/);
assert(!current.includes('unavailable'));
assert(!current.includes('play.google.com'), 'native metadata takes precedence over user agent');
assert(!current.includes('Update the Mossvale app'), 'current app has help, not a missing-capability warning');
const escaped = render({ native: true, platform: 'google', version: '<img src=x>', build: '1&2' });
assert(!escaped.includes('<img'));
assert(escaped.includes('&lt;img src=x&gt;') && escaped.includes('1&amp;2'));
const unknown = render({ native: true });
assert(unknown.includes('apps.apple.com') && unknown.includes('play.google.com'), 'unknown legacy platform offers both stores without guessing');
const main = readFileSync(new URL('../src/main.ts', import.meta.url), 'utf8');
assert.match(main, /data-settings-tab="updates">Updates/);
assert.match(main, /data-settings-page="updates" hidden>\$\{renderUpdateGuidance\(\)\}/);
assert.match(main, /if\(socialSignInRequiresUpdate\).*nativeUpdateLinks\(\)/, 'the sign-in update link remains gated by the existing missing capability check');
const config = JSON.parse(readFileSync(new URL('../mobile/app.json', import.meta.url)));
const eas = JSON.parse(readFileSync(new URL('../mobile/eas.json', import.meta.url)));
assert(legacy.includes(config.expo.android.package));
assert(ipad.includes(eas.submit.production.ios.ascAppId));
console.log('PASS update guidance: web, current/legacy Android and iOS, iPad desktop UA, missing metadata, escaping, configured store IDs and existing capability gate.');
