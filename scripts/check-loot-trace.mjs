import assert from 'node:assert/strict';
import { createLootTrace } from '../src/loot-trace.mjs';

let clock = 1000;
const create = () => createLootTrace({ realmId: 'eu', now: () => clock });
const player = { id: 'bon-id', name: 'Bon', level: 60, appearance: { className: 'ranger' }, accountId: 'private-account' };
const store = create();
assert.equal(store.active(player.id), false);
assert.equal(store.write(player.id, 'kill', { monsterId: 'golem' }), false);
assert.equal(store.report(player.id), null);
assert.equal(store.stop(player.id), null);
assert.deepEqual(store.summaries(), []);
assert.throws(() => store.start({ id: '' }, 'gm-id'), /character ID/);
assert.throws(() => store.start(player, ''), /GM character ID/);

const started = store.start(player, 'gm-id');
assert.equal(started.realmId, 'eu');
assert.equal(started.version, 1);
assert.deepEqual(started.player, { id: player.id, name: 'Bon', level: 60, className: 'ranger' });
assert.deepEqual(started.events, [{ at: clock, type: 'started', actorId: 'gm-id' }]);
assert.equal(started.expiresAt - started.startedAt, 30 * 60 * 1000);
assert.equal(JSON.stringify(started).includes('private-account'), false);
assert.equal(store.write('someone-else', 'kill'), false, 'Tracing one player must not collect other players.');
const details = { loot: { maps: 1 }, at: -1, type: 'untrusted-override' };
assert.equal(store.write(player.id, 'kill', details), true);
details.loot.maps = 100;
started.player.name = 'Changed';
started.events.length = 0;
clock += 100;
const again = store.start(player, 'another-gm');
assert.equal(again.startedAt, 1000, 'Starting an active trace must not erase or extend it.');
assert.equal(again.events.length, 2);
assert.deepEqual(again.events[1], { loot: { maps: 1 }, at: 1000, type: 'kill' });
const report = store.report(player.id);
report.events[1].loot.maps = 200;
assert.equal(store.report(player.id).events[1].loot.maps, 1, 'Reports and inputs cannot mutate stored evidence.');
const summaries = store.summaries();
assert.equal(summaries[0].active, true);
assert.equal(summaries[0].eventCount, 2);
summaries[0].player.name = 'Changed';
assert.equal(store.report(player.id).player.name, 'Bon');

const stopped = store.stop(player.id);
assert.equal(stopped.stoppedAt, clock);
assert.equal(stopped.stoppedReason, 'manual');
assert.equal(store.active(player.id), false);
assert.equal(store.write(player.id, 'ignored'), false);
assert.deepEqual(store.stop(player.id, 'changed'), stopped, 'Stopping twice must preserve the first stop reason.');
assert.equal(store.start(player, 'gm-id').events.length, 1, 'Explicitly starting a stopped trace replaces its report.');
clock += 30 * 60 * 1000;
assert.equal(store.write(player.id, 'too-late'), false);
const expired = store.report(player.id);
assert.equal(expired.stoppedAt, expired.expiresAt);
assert.equal(expired.stoppedReason, 'expired');
assert.equal(store.active(player.id), false);
assert.equal(store.stop(player.id).stoppedReason, 'expired');
assert.equal(store.summaries()[0].active, false);

store.start(player, 'gm-id');
for (let i = 0; i < 999; i++) assert.equal(store.write(player.id, 'kill', { index: i }), true);
assert.equal(store.active(player.id), false);
assert.equal(store.write(player.id, 'discarded'), false);
const capped = store.report(player.id);
assert.equal(capped.events.length, 1000);
assert.equal(capped.events[0].type, 'started');
assert.equal(capped.events.at(-1).index, 998);
assert.equal(capped.stoppedReason, 'event_limit');
for (let i = 0; i < 4; i++) store.start({ ...player, id: `player-${i}` }, 'gm-id');
store.start({ ...player, id: 'sixth-player' }, 'gm-id');
assert.equal(store.summaries().length, 5);
assert.equal(store.report(player.id), null, 'A new trace replaces the oldest stopped report when capacity is reached.');
assert.throws(() => store.start({ ...player, id: 'seventh-player' }, 'gm-id'), /Five loot traces/);
assert.equal(store.report('player-0').stoppedAt, null, 'Capacity exhaustion never evicts active evidence.');
store.stop('player-0');
store.start(player, 'gm-id');
assert.equal(store.report('player-0'), null);
store.stop(player.id);
assert.equal(store.start(player, 'gm-id').events.length, 1, 'Replacing a retained trace is allowed at capacity.');
assert.equal(store.clear(player.id), true);
assert.equal(store.report(player.id), null, 'Character deletion can erase all retained trace evidence.');
assert.equal(store.active(player.id), false);
assert.equal(store.clear(player.id), false);
clock += 30 * 60 * 1000;
store.start(player, 'gm-id');
store.start({ ...player, id: 'new-player' }, 'gm-id');
assert.equal(store.report('player-1'), null, 'Expired traces are eligible for eviction without a preceding read.');
assert.deepEqual(create().summaries(), [], 'Diagnostics are deliberately lost on server restart.');

console.log('Loot trace passed: opt-in isolation, expiry, caps, retained reports, idempotence and copy safety.');
